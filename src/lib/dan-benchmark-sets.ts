export function getBenchmarkBeatmapsetIds(family: DanBenchmarkFamily): number[] {
  if (family === "ln") return LN_BENCHMARK_BEATMAPSET_IDS;
  if (family === "ranked") return RANKED_BENCHMARK_BEATMAPSET_IDS;
  return NORMAL_BENCHMARK_BEATMAPSET_IDS;
}

export function getBenchmarkBeatmapIds(family: DanBenchmarkFamily): Set<number> | null {
  return family === "ranked" ? new Set(RANKED_BENCHMARK_BEATMAP_IDS) : null;
}

export function getBenchmarkBeatmapStarRating(beatmapId: number): number | null {
  const index = RANKED_BENCHMARK_BEATMAP_IDS.indexOf(beatmapId);
  return index >= 0 ? RANKED_BENCHMARK_STAR_RATINGS[index] ?? null : null;
}

