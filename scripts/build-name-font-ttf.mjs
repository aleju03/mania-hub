// Supporter name fonts for the drawn pictures (/api/og): satori reads no
// WOFF2, so each /fonts/name/*.woff2 gets a TTF beside it in ttf/, and the
// rules styles.css gives each font (size adjust, spacing, weight) are written
// to src/lib/og-name-fonts.ts with the x-height the size adjust needs.
//
//   node scripts/build-name-font-ttf.mjs     (needs woff2_decompress on PATH)
//
// Run after adding or changing a name font.

import { execFileSync } from "node:child_process";
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { createElement as h } from "react";
import satori from "satori";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const css = readFileSync(path.join(root, "src/styles.css"), "utf8");
const fontDir = path.join(root, "public/fonts/name");
const outDir = path.join(fontDir, "ttf");
mkdirSync(outDir, { recursive: true });

const declarations = (block) => Object.fromEntries(block.replace(/\/\*[\s\S]*?\*\//g, "").split(";").map((line) => line.trim()).filter(Boolean)
  .map((line) => [line.slice(0, line.indexOf(":")).trim(), line.slice(line.indexOf(":") + 1).trim()]));

const files = {};
for (const match of css.matchAll(/@font-face\s*{([^}]*)}/g)) {
  const family = /font-family:\s*"([^"]+)"/.exec(match[1])?.[1];
  const file = /url\("\/fonts\/name\/([^"]+)\.woff2"\)/.exec(match[1])?.[1];
  if (family && file) files[family] = file;
}

const em = (value) => (value && value.endsWith("em") ? Number(value.slice(0, -2)) : 0);

// The font's x-height in ems: its own figure, else the height of its "x".
async function xHeight(ttf) {
  const tables = {};
  for (let index = 0; index < ttf.readUInt16BE(4); index++) {
    const at = 12 + index * 16;
    tables[ttf.toString("latin1", at, at + 4)] = ttf.readUInt32BE(at + 8);
  }
  const unitsPerEm = ttf.readUInt16BE(tables.head + 18);
  const stated = ttf.readUInt16BE(tables["OS/2"]) >= 2 ? ttf.readInt16BE(tables["OS/2"] + 86) : 0;
  if (stated > 0) return stated / unitsPerEm;
  const svg = await satori(h("div", { style: { fontFamily: "F", fontSize: "1000px", lineHeight: 1, color: "#fff" } }, "x"),
    { width: 2000, height: 2000, fonts: [{ name: "F", data: ttf, weight: 400, style: "normal" }] });
  const d = /<path[^>]*\sd="([^"]+)"/.exec(svg)?.[1] ?? "";
  // On-curve points only: each segment's last pair.
  const ys = [...d.matchAll(/[MLQC]((?:-?[\d.]+[ ,]?)+)/g)].map((segment) => Number(segment[1].trim().split(/[ ,]+|(?=-)/).filter(Boolean).at(-1)));
  return (Math.max(...ys) - Math.min(...ys)) / 1000;
}

const scratch = mkdtempSync(path.join(tmpdir(), "name-fonts-"));
const rows = [];
for (const match of css.matchAll(/^\.name-font--([a-z0-9]+)\s*{([^}]*)}/gm)) {
  const rule = declarations(match[2]);
  const family = /"([^"]+)"/.exec(rule["font-family"] ?? "")?.[1];
  if (!family || !files[family]) continue;
  const file = files[family];
  copyFileSync(path.join(fontDir, `${file}.woff2`), path.join(scratch, `${file}.woff2`));
  execFileSync("woff2_decompress", [path.join(scratch, `${file}.woff2`)], { stdio: "ignore" });
  const ttf = readFileSync(path.join(scratch, `${file}.ttf`));
  writeFileSync(path.join(outDir, `${file}.ttf`), ttf);
  const adjust = Number(rule["font-size-adjust"]);
  const stroke = em((rule["-webkit-text-stroke"] ?? "").split(" ")[0]);
  rows.push(`  ${JSON.stringify(match[1])}: { file: ${JSON.stringify(file)}, weight: ${Number(rule["font-weight"]) || 400}, italic: ${rule["font-style"] === "italic"}, `
    + `scale: ${Number.isFinite(adjust) ? Number((adjust / await xHeight(ttf)).toFixed(4)) : 1}, spacing: ${em(rule["letter-spacing"])}, padBlock: ${em(rule["padding-block"])}`
    + `${stroke ? `, stroke: ${stroke}` : ""} },`);
}
rmSync(scratch, { recursive: true, force: true });

writeFileSync(path.join(root, "src/lib/og-name-fonts.ts"), `// Generated by scripts/build-name-font-ttf.mjs from the \`name-font--<id>\` rules
// in styles.css. Do not edit by hand.

export interface OgNameFont {
  /** /fonts/name/ttf/<file>.ttf */
  file: string;
  weight: number;
  italic: boolean;
  /** font-size-adjust as a factor on the font size: the adjust over the font's own x-height. */
  scale: number;
  /** letter-spacing, in em. */
  spacing: number;
  /** padding-block, in em: how far past its line the name's fill is painted. */
  padBlock: number;
  /** A stroke in the text's own colour, in em (Heavy pixel). */
  stroke?: number;
}

export const OG_NAME_FONTS: Record<string, OgNameFont> = {
${rows.join("\n")}
};
`);
console.log(`${rows.length} fonts`);
